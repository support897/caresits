// English only for now: the other language tables are partly translated.
// Set to false to bring back device-language detection and the picker.
export const ENGLISH_ONLY = !(typeof process !== "undefined" && process.env && process.env.CARESITS_ALL_LANGS === "1"); // tests set CARESITS_ALL_LANGS=1

export function currentLang() {
  if (ENGLISH_ONLY) return "en";
  try {
    const key = accountKey("caresits-lang");
    const pick = key ? localStorage.getItem(key) : null;
    if (pick && STRINGS[pick]) return pick;
    // The signed-out door has no uid to read the account's saved
    // language. Carry only a session-level display choice there.
    if (!key) {
      const doorPick = sessionStorage.getItem("caresits-door-language");
      if (doorPick && STRINGS[doorPick]) return doorPick;
    }
  } catch { /* storage may be closed */ }
  const full = (navigator.language || "en").toLowerCase();
  if (full.startsWith("yue") || full.startsWith("zh-hk") || full.startsWith("zh-tw") || full.startsWith("zh-mo")) return "yue";
  const dev = full.slice(0, 2);
  return STRINGS[dev] ? dev : "en";
}

export function setLang(code) {
  try { const key = accountKey("caresits-lang"); if (key) localStorage.setItem(key, code); } catch { /* fine */ }
  try { sessionStorage.setItem("caresits-door-language", code); } catch { /* session storage is optional */ }
}

export function learningActivityCopy(activity, lang = currentLang()) {
  if (!activity) return { title: "", howTo: "" };
  if (lang === "es") return { title: activity.titleEs || activity.title || "", howTo: activity.howToEs || activity.howTo || "", safety: activity.safetyEs || activity.safety || "" };
  return { title: activity.title || "", howTo: activity.howTo || "", safety: activity.safety || "" };
}

export function t(key, lang = currentLang(), vars = null) {
  let s = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll("{" + k + "}", String(v));
  return s;
}

// Stamp every [data-i18n] element under root from the layer.
export function applyI18n(root = document, lang = currentLang()) {
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n, lang); });
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.i18nAria, lang)); });
  root.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.setAttribute("placeholder", t(el.dataset.i18nPh, lang)); });
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
}
