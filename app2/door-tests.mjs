// ---- 4. Google + Apple doors: walk to the provider, report as it happens ----
// Apple on the twin (probed 29 Oct 2026): the project's own
// createAuthUri answer is "OPERATION_NOT_ALLOWED: Code
// flow is not enabled for Apple" — Apple sign in is not
// switched on for caresits-test. That switch lives in the
// Firebase console with the owner's Apple developer keys;
// no app code can flip it. The Apple leg therefore proves
// the app side (the door opens the provider flow) and
// names the project block exactly, instead of pretending
// the walk reached Apple.
for (const [label, btn, host] of [["Google", "#googleBtn", "accounts.google.com"], ["Apple", "#appleBtn", "appleid.apple.com"]]) {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  await page.goto(BASE + "/app2/door.html", { waitUntil: "networkidle" });
  await page.click('[data-role="family"]');
  await page.waitForSelector("#authDoor:not([hidden])", { timeout: 5000 });
  const popupPromise = page.waitForEvent("popup", { timeout: 15000 }).catch(() => null);
  await page.click(btn);
  const popup = await popupPromise;
  if (popup) {
    // The popup first lands on the Firebase auth handler,
    // which hands off to the provider. Poll until the
    // provider host stands in the URL (up to 20 s).
    let url = popup.url();
    for (let i = 0; i < 20 && !url.includes(host); i++) { await popup.waitForTimeout(1000).catch(() => {}); url = popup.url(); }
    if (label === "Apple" && !url.includes(host)) {
      const probe = await fetch(`https://identitytoolkit.googleapis.com/v1/accounts:createAuthUri?key=${KEY}`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ identifier: "probe@example.com", providerId: "apple.com", continueUri: "http://localhost:8944/app2/door.html" }) });
      const pj = await probe.json().catch(() => ({}));
      const blocked = String((pj.error && pj.error.message) || "").includes("Code flow is not enabled for Apple");
      t("Apple door: the app opens the provider flow; the TWIN project itself refuses (code flow not enabled for Apple: an owner console step, named not hidden)", url.includes("caresits-test.firebaseapp.com/__/auth/handler") && blocked, url.slice(0, 90) + " | probe: " + String((pj.error && pj.error.message) || probe.status));
      console.log("   note: Apple completion is NOT claimed: enabling Apple sign in on the project is the owner's Firebase console step.");
      await popup.close().catch(() => {});
      await page.close();
      continue;
    }
    t(`${label} door: the provider sign in opens (${host})`, url.includes(host), url.slice(0, 110));
    console.log(`   note: the ${label} walk stops at the provider's own sign in page; no ${label} test account exists, so completion is NOT claimed.`);
    await popup.close().catch(() => {});
  } else {
    const url = page.url();
    t(`${label} door: the provider sign in opens (${host})`, url.includes(host), "no popup; page at " + url.slice(0, 110));
    console.log(`   note: the ${label} walk reached ${url.slice(0, 80)}; completion is NOT claimed without a provider test account.`);
  }
  await page.close();
}

