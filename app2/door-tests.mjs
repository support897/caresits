const SHIM = "/tmp/caresits-door-shim.mjs";
writeFileSync(SHIM, `
import net from "node:net";
import http from "node:http";
const env = new URL(process.env.https_proxy || process.env.HTTPS_PROXY);
const AUTH = "Basic " + Buffer.from(decodeURIComponent(env.username) + ":" + decodeURIComponent(env.password)).toString("base64");
const isLocal = (host) => /^(127\\.0\\.0\\.1|localhost)(:\\d+)?$/.test(host);
const server = http.createServer((req, res) => {
  const target = new URL(req.url);
  const local = isLocal(target.host);
  const headers = {};
  for (const [k, v] of Object.entries(req.headers)) { if (/^(host|proxy-authorization|proxy-connection|connection)$/i.test(k)) continue; headers[k] = v; }
  if (!local) headers["Proxy-Authorization"] = AUTH;
  headers.host = target.host;
  const up = http.request({ host: local ? "127.0.0.1" : "198.19.0.1", port: local ? Number(target.port || 80) : 3128, path: local ? target.pathname + target.search : req.url, method: req.method, headers, agent: false }, (upRes) => {
    const outHeaders = {};
    for (const [k, v] of Object.entries(upRes.headers)) { if (/^(connection|keep-alive|transfer-encoding)$/i.test(k)) continue; outHeaders[k] = v; }
    res.writeHead(upRes.statusCode, outHeaders);
    upRes.pipe(res);
  });
  up.on("error", () => { try { res.destroy(); } catch {} });
  req.pipe(up);
});
server.on("connect", (req, clientSocket, head) => {
  if (isLocal(req.url)) {
    const up = net.connect(Number(req.url.split(":")[1] || 443), "127.0.0.1", () => {
      clientSocket.write("HTTP/1.1 200 Connection Established\\r\\n\\r\\n");
      if (head && head.length) up.write(head);
      up.pipe(clientSocket); clientSocket.pipe(up);
    });
    up.on("error", () => { try { clientSocket.destroy(); } catch {} });
    clientSocket.on("error", () => { try { up.destroy(); } catch {} });
    return;
  }
  const up = net.connect(3128, "198.19.0.1", () => {
    up.write("CONNECT " + req.url + " HTTP/1.1\\r\\nHost: " + req.url + "\\r\\nProxy-Authorization: " + AUTH + "\\r\\nProxy-Connection: Keep-Alive\\r\\n\\r\\n");
  });
  let buf = Buffer.alloc(0);
  const onData = (d) => {
    buf = Buffer.concat([buf, d]);
    const idx = buf.indexOf("\\r\\n\\r\\n");
    if (idx === -1) return;
    up.off("data", onData);
    const statusLine = buf.slice(0, buf.indexOf("\\r\\n")).toString("latin1");
    const rest = buf.slice(idx + 4);
    if (/ 200 /.test(statusLine)) {
      clientSocket.write("HTTP/1.1 200 Connection Established\\r\\n\\r\\n");
      if (rest.length) clientSocket.write(rest);
      if (head && head.length) up.write(head);
      up.pipe(clientSocket); clientSocket.pipe(up);
    } else { clientSocket.write("HTTP/1.1 502 Bad Gateway\\r\\n\\r\\n"); clientSocket.destroy(); up.destroy(); }
  };
  up.on("data", onData);
  up.on("error", () => { try { clientSocket.destroy(); } catch {} });
  clientSocket.on("error", () => { try { up.destroy(); } catch {} });
});
server.listen(18080, "127.0.0.1");
`);
const shim = spawn("node", [SHIM], { stdio: "ignore" });
