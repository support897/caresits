// ---- REST helpers (twin accounts + isolation reads) ----
const KEY = testFirebaseConfig.apiKey, PROJ = testFirebaseConfig.projectId;
const signIn = async (email, password) => {
  const r = await fetch(`https://identitytoolkit.googleapis.com/v1/accounts:signInWithPassword?key=${KEY}`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ email, password, returnSecureToken: true }) });
  const j = await r.json();
  if (!j.idToken) throw new Error("sign in failed for " + email + ": " + JSON.stringify(j).slice(0, 120));
  return { token: j.idToken, uid: j.localId };
};
const fsGet = async (token, path) => {
  const r = await fetch(`https://firestore.googleapis.com/v1/projects/${PROJ}/databases/(default)/documents/${path}`, { headers: { Authorization: "Bearer " + token } });
  return r.status;
};
const fsPut = async (token, path, fields) => {
  const r = await fetch(`https://firestore.googleapis.com/v1/projects/${PROJ}/databases/(default)/documents/${path}`, { method: "PATCH", headers: { Authorization: "Bearer " + token, "Content-Type": "application/json" }, body: JSON.stringify({ fields }) });
  return r.status;
};

