// Caresitters — fleet rule proof suite (TEST ONLY, twin).
// Ilse's fleet rule (29 Oct 2026): no demo way in; the door
// is sign up or sign in always; Google, Apple and email
// doors proven on Firebase; the login stays saved until
// log out; every user's data is isolated.
//
// This suite drives the REAL door (door.html + the real
// Firebase Auth SDK) against the caresits-test TWIN. It
// builds a throwaway copy of the tree in /tmp with the
// twin config swapped into firebase-config.js — the copy
// trick the parent desk ruled: test only, never shipped.
// Google and Apple walks go as far as the provider's own
// sign in page and are reported exactly as they happen:
// no provider test account exists, so no completion is
// claimed for them. Email walks complete end to end.
//
// Sandbox network shape (test rig only): Chromium cannot
// answer this sandbox's egress proxy auth challenge, so
// the suite spawns a tiny local proxy shim on
// 127.0.0.1:18080 that injects the proxy authorization
// from the environment and serves loopback directly, and
// the browser ignores certificate errors because the
// egress proxy re-signs TLS with its own CA. The shim
// source is embedded below and written to /tmp at run
// time; nothing of it ships.
